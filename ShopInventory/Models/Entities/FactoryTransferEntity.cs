using System.ComponentModel.DataAnnotations;
using Microsoft.EntityFrameworkCore;

namespace ShopInventory.Models.Entities;

/// <summary>
/// Stock handed from one side of the factory to the other: production releasing to dispatch, or
/// dispatch returning to production.
/// </summary>
/// <remarks>
/// <para>
/// Two SAP transfers make one of these. Sending posts the "out" leg from the sender's warehouse into
/// the holding warehouse (FSRW). The receiving side then accepts, part-accepts or rejects it, or the
/// sender recalls it, and that posts the "in" leg out of the holding warehouse: what was accepted to
/// the destination, and anything not accepted back to where it came from, in one document.
/// </para>
/// <para>
/// Each leg is stamped in SAP's <c>U_OrderNumber</c> with <see cref="OutOrderNumber"/> or
/// <see cref="InOrderNumber"/>, so a post whose reply was lost is found and adopted on retry rather
/// than posted twice.
/// </para>
/// </remarks>
[Index(nameof(Status), nameof(SentAtUtc))]
[Index(nameof(SourceWarehouseCode))]
[Index(nameof(DestinationWarehouseCode))]
public sealed class FactoryTransferEntity
{
    [Key]
    public int Id { get; set; }

    /// <summary>Generated by the page per send, so a submit retried after a lost reply finds this record.</summary>
    [Required]
    [MaxLength(100)]
    public string ClientRequestId { get; set; } = string.Empty;

    [Required]
    [MaxLength(20)]
    public string DepartmentCode { get; set; } = string.Empty;

    /// <summary><see cref="FactoryTransferDirections.Release"/> or <see cref="FactoryTransferDirections.Return"/>.</summary>
    [Required]
    [MaxLength(20)]
    public string Direction { get; set; } = FactoryTransferDirections.Release;

    [Required]
    [MaxLength(50)]
    public string SourceWarehouseCode { get; set; } = string.Empty;

    [Required]
    [MaxLength(50)]
    public string HoldingWarehouseCode { get; set; } = string.Empty;

    [Required]
    [MaxLength(50)]
    public string DestinationWarehouseCode { get; set; } = string.Empty;

    [Required]
    [MaxLength(500)]
    public string Reason { get; set; } = string.Empty;

    /// <summary>The truck carrying a depot delivery, written to SAP's <c>VehiclePlate</c> on both legs.</summary>
    [MaxLength(20)]
    public string? VehiclePlate { get; set; }

    /// <summary>Who drove a depot delivery; named in the remarks on both legs.</summary>
    [MaxLength(100)]
    public string? DriverName { get; set; }

    /// <summary>The depot's transfer request this delivery fulfils, closed in SAP once the truck is loaded.</summary>
    public int? SourceRequestDocEntry { get; set; }

    public int? SourceRequestDocNum { get; set; }

    public Guid SentByUserId { get; set; }

    [Required]
    [MaxLength(150)]
    public string SentByName { get; set; } = string.Empty;

    public DateTime SentAtUtc { get; set; } = DateTime.UtcNow;

    [Required]
    [MaxLength(30)]
    public string Status { get; set; } = FactoryTransferStatuses.Sending;

    public int? OutSapDocEntry { get; set; }

    public int? OutSapDocNum { get; set; }

    public DateTime? OutPostedAtUtc { get; set; }

    public int OutAttempts { get; set; }

    /// <summary>How the transfer was settled: accepted (fully or in part), rejected or recalled.</summary>
    [MaxLength(20)]
    public string? Decision { get; set; }

    public Guid? DecidedByUserId { get; set; }

    [MaxLength(150)]
    public string? DecidedByName { get; set; }

    public DateTime? DecidedAtUtc { get; set; }

    [MaxLength(500)]
    public string? DecisionReason { get; set; }

    public int? InSapDocEntry { get; set; }

    public int? InSapDocNum { get; set; }

    public DateTime? InPostedAtUtc { get; set; }

    public int InAttempts { get; set; }

    public DateTime? LastAttemptedAtUtc { get; set; }

    [MaxLength(2000)]
    public string? LastError { get; set; }

    public List<FactoryTransferLineEntity> Lines { get; set; } = [];

    public string Number => FormatNumber(Id);

    public string OutOrderNumber => $"{Number}-OUT";

    public string InOrderNumber => $"{Number}-IN";

    public static string FormatNumber(int id) => $"FT-{id:D6}";

    /// <summary>A delivery to a depot or a return from one, through DEPOTRAN rather than FSRW.</summary>
    public bool IsDepotMovement => FactoryTransferDirections.IsDepot(Direction);
}

public static class FactoryTransferDirections
{
    /// <summary>Production to dispatch.</summary>
    public const string Release = "Release";

    /// <summary>Dispatch back to production.</summary>
    public const string Return = "Return";

    /// <summary>Distribution loading a truck from the dispatch warehouses for a depot.</summary>
    public const string Delivery = "Delivery";

    /// <summary>A depot sending stock back to a dispatch warehouse.</summary>
    public const string DepotReturn = "DepotReturn";

    public static bool IsDepot(string? direction) => direction is Delivery or DepotReturn;
}

public static class FactoryTransferDecisions
{
    public const string Accepted = "Accepted";
    public const string Rejected = "Rejected";
    public const string Recalled = "Recalled";
}

/// <summary>
/// Where a factory transfer is in its life.
/// </summary>
public static class FactoryTransferStatuses
{
    /// <summary>
    /// The out leg is on its way to SAP. Only ever transient: one read back in this state was stranded
    /// mid-post, and retrying it finishes it.
    /// </summary>
    public const string Sending = "Sending";

    /// <summary>SAP refused, or did not answer, the out leg. Retry it, or cancel if it never reached SAP.</summary>
    public const string SendFailed = "SendFailed";

    /// <summary>In the holding warehouse, waiting for the receiving side.</summary>
    public const string InTransit = "InTransit";

    /// <summary>Decided; the in leg is on its way to SAP. Transient, as <see cref="Sending"/> is.</summary>
    public const string Settling = "Settling";

    /// <summary>Decided, but SAP refused or did not answer the in leg. Retrying re-posts the same decision.</summary>
    public const string SettleFailed = "SettleFailed";

    /// <summary>Every unit sent was accepted into the destination.</summary>
    public const string Accepted = "Accepted";

    /// <summary>Some units were accepted; the rest went back to the sender's warehouse.</summary>
    public const string PartiallyAccepted = "PartiallyAccepted";

    /// <summary>The receiving side turned it down; everything went back to the sender's warehouse.</summary>
    public const string Rejected = "Rejected";

    /// <summary>The sender took it back before anybody accepted it.</summary>
    public const string Recalled = "Recalled";

    /// <summary>The out leg never reached SAP and the sender abandoned it. Nothing moved.</summary>
    public const string Cancelled = "Cancelled";

    public static readonly IReadOnlyList<string> All =
    [
        Sending, SendFailed, InTransit, Settling, SettleFailed,
        Accepted, PartiallyAccepted, Rejected, Recalled, Cancelled
    ];

    /// <summary>Waiting on somebody: not yet settled and not abandoned.</summary>
    public static readonly IReadOnlyList<string> Open = [Sending, SendFailed, InTransit, Settling, SettleFailed];

    public static bool IsFinal(string status)
        => status is Accepted or PartiallyAccepted or Rejected or Recalled or Cancelled;
}
