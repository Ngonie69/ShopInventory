-- The production table, as pg_dump prints it.
CREATE TABLE "DesktopFiscalTransactions" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ClientTransactionId" character varying(100) NOT NULL UNIQUE,
    "TimestampUtc" timestamp with time zone NOT NULL,
    "DocumentType" character varying(40) NOT NULL,
    "DocNum" integer NOT NULL,
    "Status" character varying(40) NOT NULL,
    "Message" character varying(2000),
    "VerificationCode" character varying(120),
    "QRCode" character varying(2000),
    "DeviceSerialNumber" character varying(120),
    "DeviceId" character varying(120),
    "FiscalDay" character varying(40),
    "ReceiptGlobalNo" integer,
    "CardCode" character varying(50),
    "CardName" character varying(255),
    "DocTotal" numeric(18,2) NOT NULL,
    "VatSum" numeric(18,2) NOT NULL,
    "Currency" character varying(10),
    "OriginalInvoiceNumber" character varying(50),
    "RawRequest" text,
    "RawResponse" text,
    "SourceSystem" character varying(50) NOT NULL,
    "CreatedByUserId" character varying(100),
    "CreatedByUsername" character varying(100),
    "CreatedAtUtc" timestamp with time zone NOT NULL,
    "LastSyncedAtUtc" timestamp with time zone NOT NULL
);

-- A REVMax GetInvoice answer as RevmaxFiscalReceiptReader serialises InvoiceResponse.
CREATE FUNCTION revmax_answer(device text, receipt_type text, receipt_no int) RETURNS text
LANGUAGE sql AS $$
    SELECT json_build_object(
        'Code', '1', 'Message', 'Success', 'QRcode', 'https://fdms.zimra.co.zw/qr',
        'VerificationCode', 'AAAA-BBBB-CCCC-DDDD', 'VerificationLink', NULL,
        'DeviceID', device, 'DeviceSerialNumber', '8DE6996C0188', 'FiscalDay', '12',
        'Data', json_build_object('receiptType', receipt_type, 'receiptCurrency', 'USD',
                                  'receiptCounter', 7, 'receiptGlobalNo', receipt_no,
                                  'invoiceNo', coalesce(device, '?') || '-' || receipt_no))::text
$$;

CREATE FUNCTION add_row(client_id text, doc_type text, doc_num int, status text, source text,
                        device text, receipt_no int, raw text) RETURNS void
LANGUAGE sql AS $$
    INSERT INTO "DesktopFiscalTransactions"
        ("ClientTransactionId", "TimestampUtc", "DocumentType", "DocNum", "Status", "Message",
         "VerificationCode", "QRCode", "DeviceSerialNumber", "DeviceId", "FiscalDay", "ReceiptGlobalNo",
         "CardCode", "DocTotal", "VatSum", "RawResponse", "SourceSystem", "CreatedAtUtc", "LastSyncedAtUtc")
    VALUES (client_id, '2026-09-17 10:00+00', doc_type, doc_num, status, 'original message',
            CASE WHEN status = 'Fiscalised' THEN 'AAAA-BBBB-CCCC-DDDD' END,
            CASE WHEN status = 'Fiscalised' THEN 'https://fdms.zimra.co.zw/qr' END,
            '8DE6996C0188', device, '12', receipt_no,
            'SPA059 USD', 438.90, 58.90, raw, source, '2026-09-17 10:00+00', '2026-09-17 10:00+00')
$$;

