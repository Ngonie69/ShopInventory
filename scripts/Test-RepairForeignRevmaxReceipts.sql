CREATE TABLE before AS SELECT * FROM "DesktopFiscalTransactions";
CREATE TABLE expected_repaired(doc_num int PRIMARY KEY);
INSERT INTO expected_repaired VALUES (776179), (776180), (776181), (776182), (91001);

-- ===== 1. Dry run: prints, changes nothing =====
\echo '######## dry run'
\ir repair-foreign-revmax-receipts.sql

DO $$
BEGIN
    IF EXISTS (SELECT * FROM "DesktopFiscalTransactions" EXCEPT SELECT * FROM before)
       OR (SELECT count(*) FROM "DesktopFiscalTransactions") <> (SELECT count(*) FROM before) THEN
        RAISE EXCEPTION 'FAIL: the dry run changed rows';
    END IF;
    RAISE NOTICE 'PASS: the dry run changed nothing';
END $$;

-- ===== 2. Apply =====
\echo '######## apply'
\set apply 1
\ir repair-foreign-revmax-receipts.sql

DO $$
DECLARE bad text;
BEGIN
    SELECT string_agg(t."DocNum"::text, ', ') INTO bad
    FROM "DesktopFiscalTransactions" t JOIN expected_repaired e ON e.doc_num = t."DocNum"
    WHERE NOT (t."Status" = 'Not Fiscalised'
               AND t."ReceiptGlobalNo" IS NULL AND t."QRCode" IS NULL AND t."VerificationCode" IS NULL
               AND t."DeviceId" IS NULL AND t."DeviceSerialNumber" IS NULL AND t."FiscalDay" IS NULL
               AND t."Message" LIKE 'Repaired %which is not ours (device 22862)%');
    IF bad IS NOT NULL THEN RAISE EXCEPTION 'FAIL: not repaired as expected: %', bad; END IF;
    RAISE NOTICE 'PASS: the 5 foreign receipts now read Not Fiscalised with no receipt fields';

    SELECT string_agg(t."DocNum"::text, ', ') INTO bad
    FROM "DesktopFiscalTransactions" t JOIN before b ON b."Id" = t."Id"
    WHERE t."RawResponse" IS DISTINCT FROM b."RawResponse"
       OR t."ClientTransactionId" IS DISTINCT FROM b."ClientTransactionId"
       OR t."SourceSystem" IS DISTINCT FROM b."SourceSystem"
       OR t."DocNum" IS DISTINCT FROM b."DocNum";
    IF bad IS NOT NULL THEN RAISE EXCEPTION 'FAIL: identity or evidence columns changed: %', bad; END IF;
    RAISE NOTICE 'PASS: RawResponse, client id, source and DocNum kept on every row';

    SELECT string_agg(t."DocNum"::text, ', ') INTO bad
    FROM (SELECT * FROM "DesktopFiscalTransactions" EXCEPT SELECT * FROM before) t
    WHERE t."DocNum" NOT IN (SELECT doc_num FROM expected_repaired);
    IF bad IS NOT NULL THEN RAISE EXCEPTION 'FAIL: rows that must be left alone changed: %', bad; END IF;
    RAISE NOTICE 'PASS: the 8 rows that are ours, from other writers, unfound, platform-era or unparseable are untouched';

    IF EXISTS (SELECT 1 FROM "DesktopFiscalTransactions" t JOIN expected_repaired e ON e.doc_num = t."DocNum"
               WHERE t."DocNum" = 776179 AND t."Message" NOT LIKE '%receipt 8406 of device 3180 (FiscalInvoice)%') THEN
        RAISE EXCEPTION 'FAIL: the repair message does not name the foreign receipt';
    END IF;
    RAISE NOTICE 'PASS: the repair message names the foreign receipt and its device';
END $$;

-- ===== 3. Apply again: nothing left to do =====
\echo '######## apply again'
CREATE TABLE after_first AS SELECT * FROM "DesktopFiscalTransactions";
\ir repair-foreign-revmax-receipts.sql

DO $$
BEGIN
    IF EXISTS (SELECT * FROM "DesktopFiscalTransactions" EXCEPT SELECT * FROM after_first) THEN
        RAISE EXCEPTION 'FAIL: a second run changed rows';
    END IF;
    RAISE NOTICE 'PASS: a second run finds nothing and changes nothing';
END $$;

\echo 'ALL PASSED'
