"""Writes repair-stale-reposted-links.sql: points local rows at the invoices SAP holds today.

The companion of stale_reposted_links.py, which finds the rows; this rewrites them. Both read the
reposts from SAP the same way, so the old -> new mapping is never typed by hand.

What it changes, each only where the row is in the exact stale state the audit reports:

  * DesktopSales, StockReservations, InvoiceQueue: matched by the sale reference in the repost's
    Comments, and only where the row still holds the repost's OLD DocNum.
  * Invoices (local copies) and CrateTransactions: matched by old DocNum AND the repost's customer,
    and only where the invoice holding that number in SAP TODAY is not that customer's. A row created
    after the rollback can name today's holder of a reissued number, for the same customer; such a row
    is right as it stands and is listed rather than touched. Local invoice totals are mostly stored as
    0.00, so a total is compared only where one was stored.
  * DesktopCreditNotes: the memo number, where SAP's one standing memo under the credit's own
    DCN- reference (NumAtCard) is a different document from the one the row names.

Untouched on purpose: DesktopFiscalTransactions (fiscal history is filed under the old DocNum, and
#567 already flags those rows), SapCreditNoteSnapshots (SAP's own truth, re-synced from SAP).

Run with Repair-StaleRepostedLinks.ps1 -DryRun first: same output, rolled back.

    SAP_B1SESSION=<SessionId> python scripts/repair_stale_reposted_links.py
    python scripts/repair_stale_reposted_links.py --from-json reposted.json --memos-json dcn_memos.json \\
        --holders-json holders.json
"""
import argparse
import collections
import json
import os
import sys

from stale_reposted_links import MARKER, OLD, pull_from_sap, sql_text, values_block


def pull_dcn_memos(base_url, session):
    import requests
    import urllib3

    urllib3.disable_warnings()
    s = requests.Session()
    s.verify = False  # self-signed CN=kfldb; this only reads
    s.cookies.set("B1SESSION", session)
    url = (base_url + "CreditNotes?$filter=startswith(NumAtCard,'DCN-')"
           "&$select=DocEntry,DocNum,NumAtCard,Cancelled&$orderby=DocEntry")
    rows = []
    while url:
        r = s.get(url, headers={"Prefer": "odata.maxpagesize=500"}, timeout=300)
        r.raise_for_status()
        body = r.json()
        rows += body["value"]
        nxt = body.get("odata.nextLink")
        url = base_url + nxt if nxt else None
    return rows


def pull_holders(base_url, session, low, high):
    """Today's invoices numbered low..high: who holds each old DocNum now."""
    import requests
    import urllib3

    urllib3.disable_warnings()
    s = requests.Session()
    s.verify = False  # self-signed CN=kfldb; this only reads
    s.cookies.set("B1SESSION", session)
    in_range = f"$filter=DocNum ge {low} and DocNum le {high}"
    url = base_url + f"Invoices?{in_range}&$select=DocEntry,DocNum,CardCode&$orderby=DocNum"
    rows = []
    while url:
        r = s.get(url, headers={"Prefer": "odata.maxpagesize=500"}, timeout=300)
        r.raise_for_status()
        body = r.json()
        rows += body["value"]
        nxt = body.get("odata.nextLink")
        url = base_url + nxt if nxt else None

    # A pull cut short would read as "nobody holds it" and let a row be rewritten that names today's
    # holder. Numbers past the last reissued one are simply absent, so the count is what proves it.
    r = s.get(base_url + f"Invoices/$count?{in_range}", timeout=300)
    r.raise_for_status()
    if int(r.text) != len(rows):
        sys.exit(f"SAP counts {r.text} invoices numbered {low}..{high}, the pull returned {len(rows)}. Pull it again.")
    return rows


def old_numbers(reposts):
    return [int(OLD.search(r["Comments"]).group(1)) for r in reposts]


def standing_memo_per_reference(memos):
    """One standing memo per DCN- reference, or the reference is left out and named."""
    by_ref = collections.defaultdict(list)
    for m in memos:
        if m.get("Cancelled") != "tYES":
            by_ref[m["NumAtCard"]].append(m)
    single = {ref: ms[0] for ref, ms in by_ref.items() if len(ms) == 1}
    ambiguous = sorted(ref for ref, ms in by_ref.items() if len(ms) > 1)
    return single, ambiguous


def render(reposts, memos, holders):
    memo_values = ",\n".join(
        f"({sql_text(ref)},{m['DocEntry']},{m['DocNum']})" for ref, m in sorted(memos.items())) or "(NULL,NULL,NULL)"
    holder_values = ",\n".join(
        f"({h['DocNum']},{sql_text((h['CardCode'] or '').strip())})" for h in holders) or "(NULL,NULL)"

    return f"""-- Generated by scripts/repair_stale_reposted_links.py from {len(reposts)} reposted invoices,
-- {len(memos)} DCN- credit memos and today's {len(holders)} invoices numbered across the old range.
-- Do not edit by hand. Run through Repair-StaleRepostedLinks.ps1.
\\set ON_ERROR_STOP on
\\pset footer off
BEGIN;

CREATE TEMP TABLE repost(new_entry int, new_num int, old_num int, card text, ref text, total numeric, doc_date date) ON COMMIT DROP;
INSERT INTO repost VALUES
{values_block(reposts)};

CREATE TEMP TABLE dcn_memo(number text, doc_entry int, doc_num int) ON COMMIT DROP;
INSERT INTO dcn_memo VALUES
{memo_values};
DELETE FROM dcn_memo WHERE number IS NULL;

-- Who holds each old DocNum in SAP today. A local row naming that holder's customer is about the
-- holder, not the repost, and stays as it is.
CREATE TEMP TABLE holder(doc_num int, card text) ON COMMIT DROP;
INSERT INTO holder VALUES
{holder_values};
DELETE FROM holder WHERE doc_num IS NULL;

\\echo
\\echo '== Not repaired, for a person to look at'
SELECT 'Invoices' AS tbl, i."Id"::text AS row_id, i."CardCode" AS row_card, i."DocTotal" AS row_total,
       i."CreatedAt", p.card AS repost_card, p.total AS repost_total, p.old_num, p.new_num,
       CASE WHEN i."CardCode" IS DISTINCT FROM p.card THEN 'another customer''s invoice: names today''s holder'
            WHEN EXISTS (SELECT 1 FROM holder h WHERE h.doc_num = p.old_num AND h.card = i."CardCode")
                 THEN 'AMBIGUOUS: today''s holder of the number is the same customer'
            ELSE 'stored total differs from the repost''s' END AS why
  FROM "Invoices" i JOIN repost p ON p.old_num = i."SAPDocNum"
 WHERE i."CardCode" IS DISTINCT FROM p.card
    OR EXISTS (SELECT 1 FROM holder h WHERE h.doc_num = p.old_num AND h.card = i."CardCode")
    OR (i."DocTotal" <> 0 AND i."DocTotal" <> p.total)
UNION ALL
SELECT 'CrateTransactions', t."Id"::text, t."ShopCardCode", NULL, t."CreatedAt", p.card, p.total, p.old_num, p.new_num,
       CASE WHEN t."ShopCardCode" IS DISTINCT FROM p.card THEN 'another customer''s invoice: names today''s holder'
            ELSE 'AMBIGUOUS: today''s holder of the number is the same customer' END
  FROM "CrateTransactions" t JOIN repost p ON p.old_num = t."InvoiceDocNum"
 WHERE t."ShopCardCode" IS DISTINCT FROM p.card
    OR EXISTS (SELECT 1 FROM holder h WHERE h.doc_num = p.old_num AND h.card = t."ShopCardCode")
 ORDER BY 1, 8;

\\echo
\\echo '== Rows repaired, per table'
WITH u AS (
    UPDATE "DesktopSales" s SET "SapDocEntry" = p.new_entry, "SapDocNum" = p.new_num
      FROM repost p
     WHERE p.ref = s."ExternalReferenceId" AND s."SapDocNum" = p.old_num
    RETURNING 1)
SELECT 'DesktopSales' AS tbl, count(*) AS rows FROM u;

WITH u AS (
    UPDATE "StockReservations" r SET "SAPDocEntry" = p.new_entry, "SAPDocNum" = p.new_num
      FROM repost p
     WHERE p.ref = r."ExternalReferenceId" AND r."SAPDocNum" = p.old_num
    RETURNING 1)
SELECT 'StockReservations' AS tbl, count(*) AS rows FROM u;

WITH u AS (
    UPDATE "InvoiceQueue" q SET "SapDocEntry" = p.new_entry::text, "SapDocNum" = p.new_num
      FROM repost p
     WHERE p.ref = q."ExternalReference" AND q."SapDocNum" = p.old_num
    RETURNING 1)
SELECT 'InvoiceQueue' AS tbl, count(*) AS rows FROM u;

WITH u AS (
    UPDATE "Invoices" i SET "SAPDocEntry" = p.new_entry, "SAPDocNum" = p.new_num
      FROM repost p
     WHERE p.old_num = i."SAPDocNum" AND p.card = i."CardCode"
       AND (i."DocTotal" = 0 OR i."DocTotal" = p.total)
       AND NOT EXISTS (SELECT 1 FROM holder h WHERE h.doc_num = p.old_num AND h.card = i."CardCode")
    RETURNING 1)
SELECT 'Invoices' AS tbl, count(*) AS rows FROM u;

WITH u AS (
    UPDATE "CrateTransactions" t SET "InvoiceDocEntry" = p.new_entry, "InvoiceDocNum" = p.new_num
      FROM repost p
     WHERE p.old_num = t."InvoiceDocNum" AND p.card = t."ShopCardCode"
       AND NOT EXISTS (SELECT 1 FROM holder h WHERE h.doc_num = p.old_num AND h.card = t."ShopCardCode")
    RETURNING 1)
SELECT 'CrateTransactions' AS tbl, count(*) AS rows FROM u;

\\echo
\\echo '== Till credits whose memo number is repaired (old -> SAP''s memo under the credit''s own reference)'
WITH old AS (
    SELECT d."Id", d."SapDocEntry" AS was_entry, d."SapDocNum" AS was_memo
      FROM "DesktopCreditNotes" d JOIN dcn_memo m ON m.number = d."Number"
     WHERE d."SapDocNum" IS NOT NULL
       AND (d."SapDocNum" IS DISTINCT FROM m.doc_num OR d."SapDocEntry" IS DISTINCT FROM m.doc_entry)),
u AS (
    UPDATE "DesktopCreditNotes" d SET "SapDocEntry" = m.doc_entry, "SapDocNum" = m.doc_num
      FROM dcn_memo m, old
     WHERE d."Number" = m.number AND old."Id" = d."Id"
    RETURNING d."Number", old.was_memo, old.was_entry, d."SapDocNum" AS now_memo, d."SapDocEntry" AS now_entry)
SELECT * FROM u ORDER BY 1;

\\echo
\\echo '== Proof: no sale row of a reposted sale still holds the repost''s OLD number'
DO $$
DECLARE n int;
BEGIN
    SELECT count(*) INTO n FROM (
        SELECT s."ExternalReferenceId" AS ref, s."SapDocNum" AS num FROM "DesktopSales" s
        UNION ALL SELECT r."ExternalReferenceId", r."SAPDocNum" FROM "StockReservations" r
        UNION ALL SELECT q."ExternalReference", q."SapDocNum" FROM "InvoiceQueue" q) x
      JOIN repost p ON p.ref = x.ref AND x.num = p.old_num;
    IF n <> 0 THEN
        RAISE EXCEPTION '% sale rows still hold an old DocNum; nothing was committed', n;
    END IF;
    RAISE NOTICE 'No sale row of a reposted sale holds its old DocNum.';
END $$;

\\if :{{?dryrun}}
\\echo
\\echo 'DRY RUN: rolled back. Nothing was changed.'
ROLLBACK;
\\else
COMMIT;
\\echo 'Committed.'
\\endif
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--from-json", help="a saved pull of the reposted invoices")
    ap.add_argument("--memos-json", help="a saved pull of the DCN- credit memos")
    ap.add_argument("--holders-json", help="a saved pull of today's invoices across the old DocNum range")
    ap.add_argument("--base-url", default="https://10.10.10.6:50000/b1s/v1/")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                                  "repair-stale-reposted-links.sql"))
    args = ap.parse_args()

    session = os.environ.get("SAP_B1SESSION")
    if (not args.from_json or not args.memos_json or not args.holders_json) and not session:
        sys.exit("Set SAP_B1SESSION to a production session id, or pass --from-json, --memos-json and --holders-json.")

    if args.from_json:
        with open(args.from_json, encoding="utf-8") as f:
            reposts = json.load(f)
    else:
        reposts = pull_from_sap(args.base_url, session)

    if args.memos_json:
        with open(args.memos_json, encoding="utf-8") as f:
            memos = json.load(f)
    else:
        memos = pull_dcn_memos(args.base_url, session)

    reposts = [r for r in reposts if (r.get("Comments") or "").startswith(MARKER)]
    single, ambiguous = standing_memo_per_reference(memos)

    olds = old_numbers(reposts)
    if args.holders_json:
        with open(args.holders_json, encoding="utf-8") as f:
            holders = json.load(f)
    else:
        holders = pull_holders(args.base_url, session, min(olds), max(olds))

    if not holders:
        sys.exit("No invoices hold any of the old numbers, which cannot be right. Pull it again.")

    with open(args.out, "w", encoding="ascii", errors="strict", newline="\n") as f:
        f.write(render(reposts, single, holders))

    print(f"{len(reposts)} reposts, {len(single)} DCN- memos, {len(holders)} holders -> {args.out}")
    if ambiguous:
        print(f"Left out, more than one standing memo under the reference: {', '.join(ambiguous)}")


if __name__ == "__main__":
    main()
